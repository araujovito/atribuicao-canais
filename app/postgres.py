"""Conexões PostgreSQL e esquema persistente da aplicação."""
from __future__ import annotations

import re

import psycopg
from psycopg import sql


class Linha(dict):
    """Linha acessível por nome ou posição, como nas consultas existentes."""
    def __getitem__(self, chave):
        return tuple(self.values())[chave] if isinstance(chave, int) else super().__getitem__(chave)

    def __iter__(self):
        return iter(self.values())


def linha_factory(cursor):
    nomes = [c.name for c in (cursor.description or ())]
    return lambda valores: Linha(zip(nomes, valores, strict=True))


ESQUEMA = """
CREATE TABLE IF NOT EXISTS eventos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_evento TEXT, anon_id TEXT NOT NULL,
 pessoa_id TEXT, tipo TEXT NOT NULL CHECK (tipo IN ('visita', 'conversao')),
 canal TEXT, utm_source TEXT, utm_medium TEXT, utm_campaign TEXT, referrer_host TEXT,
 aparelho TEXT, valor DOUBLE PRECISION NOT NULL DEFAULT 0, momento TEXT NOT NULL,
 UNIQUE (anon_id, id_evento)
);
CREATE INDEX IF NOT EXISTS eventos_anon ON eventos (anon_id);
CREATE INDEX IF NOT EXISTS eventos_pessoa ON eventos (pessoa_id);
CREATE INDEX IF NOT EXISTS eventos_momento ON eventos (momento);
CREATE TABLE IF NOT EXISTS vinculos (anon_id TEXT NOT NULL, pessoa_id TEXT NOT NULL,
 momento TEXT NOT NULL, PRIMARY KEY (anon_id, pessoa_id));
CREATE TABLE IF NOT EXISTS consentimentos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anon_id TEXT NOT NULL, versao TEXT NOT NULL, aceito INTEGER NOT NULL,
 juncao INTEGER NOT NULL DEFAULT 0, momento TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS consentimentos_anon ON consentimentos (anon_id);
CREATE TABLE IF NOT EXISTS etapas (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anon_id TEXT NOT NULL, etapa TEXT NOT NULL CHECK (etapa IN ('login', 'carrinho')), momento TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS etapas_anon ON etapas (anon_id);
CREATE TABLE IF NOT EXISTS experimentos (anon_id TEXT NOT NULL, canal TEXT NOT NULL,
 grupo TEXT NOT NULL CHECK (grupo IN ('tratamento', 'controle')), momento TEXT NOT NULL,
 PRIMARY KEY (anon_id, canal));
CREATE TABLE IF NOT EXISTS verdade (canal TEXT PRIMARY KEY, compras DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS pedidos_exclusao (pessoa_id TEXT PRIMARY KEY, codigo_hash TEXT NOT NULL,
 expira TEXT NOT NULL, tentativas INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS versao (id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1), n BIGINT NOT NULL);
INSERT INTO versao (id, n) VALUES (1, 0) ON CONFLICT (id) DO NOTHING;
CREATE OR REPLACE FUNCTION incrementar_versao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN UPDATE versao SET n = n + 1 WHERE id = 1; RETURN NULL; END $$;
"""


class Conexao:
    def __init__(self, url: str, schema: str = "public", criar: bool = True):
        if schema not in ("public", "ga4"):
            raise ValueError("esquema desconhecido")
        self.raw = psycopg.connect(url, autocommit=True, row_factory=linha_factory)
        self.schema = schema
        if criar:
            with self.raw.transaction():
                # Serializa a primeira instalação; uma abertura posterior não
                # altera funções, gatilhos ou dados já existentes.
                self.raw.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", ("atribuicao:" + schema,))
                existe = self.raw.execute("SELECT to_regclass(%s)", (schema + ".eventos",)).fetchone()[0]
                self.raw.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {} ").format(sql.Identifier(schema)))
                self.raw.execute(sql.SQL("SET search_path TO {} ").format(sql.Identifier(schema)))
                if not existe:
                    self.raw.execute(ESQUEMA)
                    for tabela in ("eventos", "vinculos", "etapas", "experimentos", "verdade"):
                        self.raw.execute(sql.SQL("CREATE TRIGGER versao_alteracao AFTER INSERT OR UPDATE OR DELETE ON {} "
                                                 "FOR EACH STATEMENT EXECUTE FUNCTION incrementar_versao()")
                                         .format(sql.Identifier(tabela)))
        else:
            self.raw.execute(sql.SQL("SET search_path TO {} ").format(sql.Identifier(schema)))
        self._transacoes = []

    def __enter__(self):
        transacao = self.raw.transaction()
        transacao.__enter__()
        self._transacoes.append(transacao)
        return self

    def __exit__(self, *args):
        return self._transacoes.pop().__exit__(*args)

    def execute(self, consulta, parametros=()):
        return self.raw.execute(self._sql(consulta), parametros)

    def executemany(self, consulta, parametros):
        cursor = self.raw.cursor()
        cursor.executemany(self._sql(consulta), parametros)
        return cursor

    def close(self):
        self.raw.close()

    @staticmethod
    def _sql(consulta: str) -> str:
        consulta = consulta.replace("?", "%s")
        if re.search(r"INSERT\s+OR\s+IGNORE", consulta, flags=re.I):
            consulta = re.sub(r"INSERT\s+OR\s+IGNORE", "INSERT", consulta, flags=re.I)
            consulta = consulta.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
        return consulta
